# Draws the app icon: an original pixel-art pet hatching from its egg, on a
# transparent background (Android, store art) and on a soft gradient for iOS, which allows no
# transparency in app icons.
import sys, glob, re
from PIL import Image, ImageDraw

# 32 x 32 sprite, one character per pixel
SPRITE = """
................................
..............OOOOO.............
............OOWWWWWOO...........
...........OWWWWWWWWWO..........
..........OWWWWWWWWWWWO.........
.........OWWWWWWWWWWWWWO........
........OWWWWWWWWWWWWWWWO.......
........OWWWKKWWWWWKKWWWO.......
.......OWWWKKKKWWWKKKKWWWO......
.......OWWWKWKKWWWKWKKWWWO......
.......OWWWKKKKWWWKKKKWWWO......
.......OWCCWKKWWWWWKKWCCWO......
.......OWCCWWWWKWKWWWWCCWO......
.......OWWWWWWWWKWWWWWWWWO......
.......OWWWWWWWWWWWWWWWWWO......
.......OYYOYYOYYOYYOYYOYYO......
.......OYYYYYYYYYYYYYYYYYO......
.......OYYYYYYYYYYYYYYYYYO......
.......OYYYYYYYYYYYYYYYYYO......
........OYYYYYYYYYYYYYYYO.......
........OYYYYYYYYYYYYYYYO.......
.........OYYYYYYYYYYYYYO........
..........OOYYYYYYYYYOO.........
............OOOOOOOOO...........
................................
"""
COL = {
    'O': (60, 40, 70, 255),     # outline
    'W': (255, 250, 235, 255),  # the pet, cream
    'K': (45, 30, 50, 255),     # eyes, mouth
    'C': (255, 150, 170, 255),  # cheeks
    'Y': (255, 205, 90, 255),   # eggshell
}

def sprite(size):
    rows = [r for r in SPRITE.strip('\n').split('\n')]
    s = Image.new('RGBA', (32, 32), (0, 0, 0, 0))
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch in COL:
                s.putpixel((x, y), COL[ch])
    # centre the drawing, keep a margin, scale with hard pixels
    bbox = s.getbbox()
    s = s.crop(bbox)
    w, h = s.size
    scale = int(size * 0.8 / max(w, h))
    big = s.resize((w * scale, h * scale), Image.NEAREST)
    out = Image.new('RGBA', (size, size), (0, 0, 0, 0))
    out.paste(big, ((size - big.width) // 2, (size - big.height) // 2), big)
    return out

S = 1024
transparent = sprite(S)
bg = Image.new('RGBA', (S, S))
d = ImageDraw.Draw(bg)
for y in range(S):  # soft sky gradient, blue to lilac
    t = y / S
    d.line([(0, y), (S, y)], fill=(int(120 + 80 * t), int(190 - 20 * t), int(250 - 10 * t), 255))
for (x, y, r) in [(200, 210, 26), (830, 260, 20), (760, 840, 24), (170, 780, 18)]:  # sparkles
    d.polygon([(x, y - r * 2), (x + r // 2, y - r // 2), (x + r * 2, y), (x + r // 2, y + r // 2), (x, y + r * 2), (x - r // 2, y + r // 2), (x - r * 2, y), (x - r // 2, y - r // 2)], fill=(255, 255, 255, 230))
ios = Image.alpha_composite(bg, transparent).convert('RGB')

out = sys.argv[1]
transparent.save(f'{out}/icon-transparent-1024.png')
ios.save(f'{out}/icon-1024.png')
for f in glob.glob('ios/Runner/Assets.xcassets/AppIcon.appiconset/Icon-App-*.png'):
    m = re.search(r'(\d+(?:\.\d+)?)x\d+(?:\.\d+)?@(\d)x', f)
    px = int(round(float(m.group(1)) * int(m.group(2))))
    ios.resize((px, px), Image.LANCZOS).save(f)
for dpi, px in {'mdpi': 48, 'hdpi': 72, 'xhdpi': 96, 'xxhdpi': 144, 'xxxhdpi': 192}.items():
    transparent.resize((px, px), Image.NEAREST if px % 32 == 0 else Image.LANCZOS).save(f'android/app/src/main/res/mipmap-{dpi}/ic_launcher.png')
print('icons written')
