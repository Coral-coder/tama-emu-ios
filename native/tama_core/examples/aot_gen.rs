// Native code for the built-in ROMs: plays each dump for a while (keys, wheel, awake), takes the
// blocks it ran often, and writes them as Rust functions to src/aot_gen/blocks.rs (ignored by
// git: made at build time from the decrypted dumps, never committed).
//   cargo run --release --example aot_gen -- <out.rs> <dump.bin>...
use std::collections::BTreeMap;
use std::ffi::CString;
use std::fmt::Write;
fn main() {
    let a: Vec<String> = std::env::args().collect();
    let out = &a[1];
    let secs: u64 = std::env::var("AOT_SECONDS").ok().and_then(|s| s.parse().ok()).unwrap_or(90);
    let mut all: BTreeMap<(u32, u64, u32), (u64, String)> = BTreeMap::new();
    for dump in &a[2..] {
        unsafe {
            let t = tama_core::tama_new();
            let p = CString::new(dump.clone()).unwrap();
            if tama_core::tama_load(t, p.as_ptr(), 0x5AAF34FB, 1) != 1 {
                eprintln!("{}: not a Paradise dump, skipped", dump);
                continue;
            }
            tama_core::tama_sync_clock(t, 30_000_000);
            tama_core::tama_auto_date(t, 120);
            let cps = tama_core::tama_cycles_per_second();
            for tenth in 0..secs * 10 {
                // all three keys and the wheel in turn: menus, games, animations, the field
                if tenth % 20 == 5 { tama_core::tama_press(t, [0x09u32, 0x0B, 0x0A, 0x0B, 0x0B][(tenth / 20 % 5) as usize]); }
                if tenth % 20 == 6 { tama_core::tama_release_all(t); }
                if tenth % 13 == 7 { tama_core::tama_turn(t, (tenth % 26 == 7) as i32); }
                if tama_core::tama_sleeping(t) == 1 { tama_core::tama_wake(t); }
                tama_core::tama_run(t, cps / 10, 600000);
            }
            let blocks = tama_core::recomp_emit(t, 50);
            eprintln!("{}: {} hot native blocks", dump, blocks.len());
            for (pc, hash, len, hits, f) in blocks {
                let e = all.entry((pc, hash, len)).or_insert((0, f));
                e.0 += hits;
            }
        }
    }
    let mut s = String::new();
    s.push_str("// Generated by examples/aot_gen.rs from the built-in dumps. Not to be committed.\n");
    s.push_str("#![allow(unused_mut, clippy::all)]\nuse super::*;\n\n");
    for (i, (_, (_, f))) in all.iter().enumerate() {
        writeln!(s, "fn b{}(m: &mut Machine) -> (u32, u32, bool) {{\n{}}}\n", i, f).unwrap();
    }
    // sorted by address (the BTreeMap order); several blocks can share one: the first match
    // on address is searched from, see the lookup
    s.push_str("pub(super) static AOT: &[(u32, u64, u32, AotFn)] = &[\n");
    for (i, ((pc, hash, len), _)) in all.iter().enumerate() {
        writeln!(s, "    (0x{:X}, 0x{:X}, {}, b{}),", pc, hash, len, i).unwrap();
    }
    s.push_str("];\n");
    std::fs::create_dir_all(std::path::Path::new(out).parent().unwrap()).ok();
    std::fs::write(out, s).unwrap();
    eprintln!("{} blocks written to {}", all.len(), out);
}
